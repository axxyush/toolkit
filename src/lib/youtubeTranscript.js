export function extractVideoId(input) {
  const value = input.trim();
  if (!value) return null;
  if (/^[\w-]{11}$/.test(value)) return value;

  try {
    const url = new URL(value);
    if (url.hostname.includes('youtu.be')) {
      return url.pathname.slice(1).split('/')[0] || null;
    }
    if (url.searchParams.get('v')) return url.searchParams.get('v');
    const parts = url.pathname.split('/').filter(Boolean);
    const embedIndex = parts.findIndex((p) => p === 'embed' || p === 'shorts');
    if (embedIndex >= 0 && parts[embedIndex + 1]) return parts[embedIndex + 1];
  } catch {
    return null;
  }
  return null;
}

function pickCaptionTrack(tracks) {
  if (!tracks?.length) return null;
  return (
    tracks.find((t) => t.languageCode === 'en' && t.kind !== 'asr') ||
    tracks.find((t) => (t.languageCode || '').startsWith('en')) ||
    tracks.find((t) => t.kind !== 'asr') ||
    tracks[0]
  );
}

function parseJson3Captions(data) {
  const events = data?.events || [];
  return events
    .filter((event) => Array.isArray(event.segs))
    .map((event) => event.segs.map((seg) => seg.utf8 || '').join(''))
    .join(' ')
    .replace(/\n+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function decodeEntities(text) {
  const el = document.createElement('textarea');
  el.innerHTML = text;
  return el.value;
}

function parseTimedTextXml(xml) {
  const doc = new DOMParser().parseFromString(xml, 'text/xml');
  return [...doc.querySelectorAll('text')]
    .map((node) => decodeEntities(node.textContent || '').replace(/\s+/g, ' ').trim())
    .filter(Boolean)
    .join('\n');
}

async function fetchCaptionText(baseUrl) {
  const cleaned = baseUrl.replace(/([?&])fmt=[^&]*/g, '$1').replace(/[?&]$/, '');
  const jsonUrl = `${cleaned}${cleaned.includes('?') ? '&' : '?'}fmt=json3`;

  const jsonRes = await fetch(
    `/api/youtube/captions?url=${encodeURIComponent(jsonUrl)}`
  );
  if (jsonRes.ok) {
    const raw = await jsonRes.text();
    try {
      const parsed = parseJson3Captions(JSON.parse(raw));
      if (parsed) return parsed;
    } catch {
      // fall through
    }
    if (raw.includes('<text')) {
      const parsed = parseTimedTextXml(raw);
      if (parsed) return parsed;
    }
  }

  const xmlRes = await fetch(
    `/api/youtube/captions?url=${encodeURIComponent(cleaned)}`
  );
  if (!xmlRes.ok) {
    throw new Error(`Caption download failed (${xmlRes.status}).`);
  }
  const xml = await xmlRes.text();
  if (xml.includes('<text')) {
    const parsed = parseTimedTextXml(xml);
    if (parsed) return parsed;
  }
  throw new Error('Captions were empty.');
}

export async function fetchYouTubeTranscript(videoId) {
  const res = await fetch('/api/youtube/player', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ videoId }),
  });

  if (res.status === 404) {
    throw new Error(
      'YouTube proxy is missing. Stop the server and run npm start again from the toolkit folder.'
    );
  }

  if (!res.ok) {
    let detail = '';
    try {
      const err = await res.json();
      detail = err.error ? `: ${err.error}` : '';
    } catch {
      // ignore
    }
    throw new Error(`Could not reach YouTube (${res.status})${detail}`);
  }

  const data = await res.json();
  const title = data?.videoDetails?.title || 'YouTube video';
  const playability = data?.playabilityStatus?.status;
  if (playability && playability !== 'OK') {
    throw new Error(data?.playabilityStatus?.reason || 'Video is unavailable.');
  }

  const tracks = data?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
  const track = pickCaptionTrack(tracks);
  if (!track?.baseUrl) {
    throw new Error(
      'No captions/subtitles found on this video. Auto-generated or uploaded captions must be enabled.'
    );
  }

  const text = await fetchCaptionText(track.baseUrl);
  return {
    title,
    text,
    language: track.languageCode,
    autoGenerated: track.kind === 'asr',
  };
}
