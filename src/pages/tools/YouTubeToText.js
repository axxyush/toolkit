import { useState } from 'react';
import ToolShell from '../../components/ToolShell';
import { tools } from '../../data/tools';
import { extractVideoId, fetchYouTubeTranscript } from '../../lib/youtubeTranscript';

const tool = tools.find((t) => t.id === 'youtube-to-text');

export default function YouTubeToText() {
  const [url, setUrl] = useState('');
  const [transcript, setTranscript] = useState('');
  const [title, setTitle] = useState('');
  const [meta, setMeta] = useState('');
  const [status, setStatus] = useState('');
  const [loading, setLoading] = useState(false);

  const extract = async () => {
    const videoId = extractVideoId(url);
    if (!videoId) {
      setStatus('Paste a valid YouTube URL or 11-character video ID.');
      return;
    }

    setLoading(true);
    setStatus('Fetching captions…');
    setTranscript('');
    setTitle('');
    setMeta('');

    try {
      const result = await fetchYouTubeTranscript(videoId);
      setTitle(result.title);
      setTranscript(result.text);
      setMeta(
        [
          result.language ? `Language: ${result.language}` : null,
          result.autoGenerated ? 'Auto-generated captions' : 'Uploaded captions',
        ]
          .filter(Boolean)
          .join(' · ')
      );
      setStatus('Captions loaded.');
    } catch (err) {
      setStatus(err.message || 'Could not fetch captions.');
    } finally {
      setLoading(false);
    }
  };

  const copy = async () => {
    if (!transcript) return;
    await navigator.clipboard.writeText(transcript);
    setStatus('Copied to clipboard.');
  };

  const download = () => {
    if (!transcript) return;
    const blob = new Blob([transcript], { type: 'text/plain;charset=utf-8' });
    const link = document.createElement('a');
    link.href = URL.createObjectURL(blob);
    link.download = `${(title || 'youtube-transcript').replace(/[^\w.-]+/g, '_')}.txt`;
    link.click();
    URL.revokeObjectURL(link.href);
  };

  const isError =
    status &&
    !status.startsWith('Captions loaded') &&
    !status.startsWith('Copied') &&
    !status.startsWith('Fetching');

  return (
    <ToolShell tool={tool}>
      <div className="stack">
        <div className="field">
          <label htmlFor="yt-url">YouTube URL</label>
          <input
            id="yt-url"
            className="input"
            value={url}
            onChange={(e) => setUrl(e.target.value)}
            placeholder="https://www.youtube.com/watch?v=..."
          />
        </div>

        <div className="row">
          <button
            type="button"
            className="btn btn-primary"
            onClick={extract}
            disabled={loading}
          >
            {loading ? 'Fetching…' : 'Extract captions'}
          </button>
          <button
            type="button"
            className="btn btn-ghost"
            onClick={copy}
            disabled={!transcript}
          >
            Copy
          </button>
          <button
            type="button"
            className="btn btn-ghost"
            onClick={download}
            disabled={!transcript}
          >
            Download .txt
          </button>
        </div>

        {status && <p className={`status ${isError ? 'error' : 'ok'}`}>{status}</p>}
        {title && <p className="hint">Video: {title}{meta ? ` · ${meta}` : ''}</p>}

        <div className="field">
          <label htmlFor="yt-text">Transcript</label>
          <textarea
            id="yt-text"
            className="textarea"
            style={{ minHeight: 280 }}
            value={transcript}
            onChange={(e) => setTranscript(e.target.value)}
            placeholder="Captions will appear here. You can also paste transcript text manually."
          />
        </div>
      </div>
    </ToolShell>
  );
}
